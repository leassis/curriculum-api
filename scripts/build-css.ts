import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Compiles the admin stylesheet (Tailwind v4) and vendors the admin fonts into TS modules,
 * so the admin ships its assets inside the package like `htmx.generated.ts`.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const staticDir = join(root, "src/admin/static");
const banner = "// Generated by `pnpm build:css`. Do not edit.\n";

const out = join(mkdtempSync(join(tmpdir(), "admin-css-")), "admin.css");
execFileSync(
  join(root, "node_modules/.bin/tailwindcss"),
  ["-i", join(root, "src/admin/styles/admin.css"), "-o", out, "--minify"],
  { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
);
const css = readFileSync(out, "utf8");
const version = createHash("sha256").update(css).digest("hex").slice(0, 10);
writeFileSync(
  join(staticDir, "admin-css.generated.ts"),
  `${banner}export const ADMIN_CSS_VERSION = ${JSON.stringify(version)};\nexport default ${JSON.stringify(css)};\n`,
);
console.log(`wrote admin-css.generated.ts (${css.length} bytes, v${version})`);

const fonts = {
  "inter.woff2": "@fontsource-variable/inter/files/inter-latin-wght-normal.woff2",
  "space-grotesk.woff2":
    "@fontsource-variable/space-grotesk/files/space-grotesk-latin-wght-normal.woff2",
  "jetbrains-mono.woff2":
    "@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2",
};
const entries = Object.entries(fonts).map(([name, file]) => {
  const base64 = readFileSync(join(root, "node_modules", file)).toString("base64");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(base64)},`;
});
writeFileSync(
  join(staticDir, "fonts.generated.ts"),
  `${banner}/** Base64 woff2 files (latin subset, variable weight) from the pinned @fontsource-variable packages. */\nexport const FONTS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`wrote fonts.generated.ts (${Object.keys(fonts).length} fonts)`);
