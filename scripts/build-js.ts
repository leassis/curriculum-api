import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Compiles the admin page scripts (`src/admin/<page>/client.ts`, real TypeScript with DOM types)
 * into minified IIFE strings, written to committed `src/admin/static/<page>-js.generated.ts` modules
 * that the page routes serve. `--check` verifies the committed files are up to date.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const banner = "// Generated by `pnpm build:js`. Do not edit.\n";

/** One entry per served script: source folder and the exported constant. */
export const CLIENTS = [
  { page: "career", name: "CAREER_JS" },
  { page: "chat-page", name: "CHAT_PAGE_JS" },
  { page: "chats", name: "CHATS_JS" },
  { page: "personal-info", name: "UI_JS" },
  { page: "print", name: "PRINT_JS" },
  { page: "resumes", name: "EDITOR_JS" },
] as const;

/** Generated file path (relative to the repo root) and its expected content, per client. */
export async function buildClients(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  for (const { page, name } of CLIENTS) {
    const result = await build({
      entryPoints: [join(root, "src/admin", page, "client.ts")],
      bundle: true,
      minify: true,
      format: "iife",
      target: "es2020",
      platform: "browser",
      tsconfig: join(root, "src/admin/tsconfig.client.json"),
      write: false,
      legalComments: "none",
      logLevel: "warning",
    });
    const js = (result.outputFiles[0]?.text ?? "").trim();
    files.set(
      `src/admin/static/${page}-js.generated.ts`,
      `${banner}export const ${name} = ${JSON.stringify(`${js}\n`)};\n`,
    );
  }
  return files;
}

const entry = process.argv[1];
if (entry && resolve(entry) === fileURLToPath(import.meta.url)) {
  const files = await buildClients();
  if (process.argv.includes("--check")) {
    const stale = [...files].filter(([path, text]) => {
      try {
        return readFileSync(join(root, path), "utf8") !== text;
      } catch {
        return true;
      }
    });
    for (const [path] of stale) console.error(`${path} is out of date: run \`pnpm build:js\``);
    if (stale.length > 0) process.exit(1);
  } else {
    for (const [path, text] of files) {
      writeFileSync(join(root, path), text);
      console.log(`wrote ${path} (${text.length} bytes)`);
    }
  }
}
